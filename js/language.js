  function applyRules(text) {
    for (const [re, rep] of RULES) {
      if (rep !== null && re.test(text)) return text.replace(re, rep);
    }
    return null;
  }

  function get() {
    try { return localStorage.getItem(KEY) === "en" ? "en" : "ar"; }
    catch (e) { return "ar"; }
  }
  // Longer phrases first, so "الدرس التالي" wins over "الدرس".
  // Only keys with at least two Arabic letters are used inside longer text,
  // which keeps single letters such as "و" from breaking ordinary words.
  let phraseKeys = null;
  function getPhraseKeys() {
    if (!phraseKeys) {
      phraseKeys = Object.keys(dictionary)
        .filter(k => (k.match(/[\u0600-\u06FF]/g) || []).length >= 2)
        .sort((a, b) => b.length - a.length);
    }
    return phraseKeys;
  }
  function translatePhrases(text) {
    let out = text
      .replace(/،/g, ",")                              // فاصلة عربي
      .replace(/(^|[\s,])و(?=\d)/g, "$1and ")          // "و2" => "and 2"
      .replace(/(\d+) كلمة(?![\u0600-\u06FF])/g, "$1 words")
      .replace(/(\d+) كلمات(?![\u0600-\u06FF])/g, "$1 words")
      .replace(/كلمتين/g, "two words");
    for (const k of getPhraseKeys()) {
      if (out.includes(k)) out = out.split(k).join(dictionary[k]);
    }
    return out;
  }
  function t(value) {
    const text = String(value);
    if (get() !== "en") return text;
    if (dictionary[text]) return dictionary[text];
    const ruled = applyRules(text);
    if (ruled) return ruled;
    return /[\u0600-\u06FF]/.test(text) ? translatePhrases(text) : text;
  }
  function set(lang) {
    const next = lang === "en" ? "en" : "ar";
    try { localStorage.setItem(KEY, next); } catch (e) {}
    document.documentElement.lang = next;
    document.documentElement.dir = next === "en" ? "ltr" : "rtl";
    document.documentElement.dataset.language = next;
  }
  function toggle() { set(get() === "ar" ? "en" : "ar"); }
  return { get, t, set, toggle };
